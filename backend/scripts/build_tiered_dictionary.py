def load_collins_words():
    """Load all words from Collins Scrabble Words dictionary."""
    words = set()
    if not COLLINS_FILE.exists():
        print(f"Warning: Collins file not found at {COLLINS_FILE}")
        return words

    with open(COLLINS_FILE, 'r', encoding='utf-8') as f:
        for i, line in enumerate(f):
            if i < 2:  # Skip header
                continue
            word = line.strip().upper()
            if word and 3 <= len(word) <= 7:
                words.add(word)
    return words


def build_tiered_dictionary():
    """Build the tiered dictionary structure."""
    print("Loading Collins dictionary...")
    all_words = load_collins_words()
    print(f"Loaded {len(all_words):,} words (3-7 letters)")

    # Combine all guaranteed common words
    all_common = COMMON_3 | COMMON_4 | COMMON_5 | COMMON_6 | COMMON_7

    # Build tiered structure
    tiered = {
        "common": {"3": [], "4": [], "5": [], "6": [], "7": []},
        "rare": {"3": [], "4": [], "5": [], "6": [], "7": []}
    }

    # Also track all words for flat output
    all_included = set()

    for word in sorted(all_words):
        length = str(len(word))

        if word in all_common:
            tiered["common"][length].append(word)
            all_included.add(word)
        else:
            # Apply basic filters for rare words
            if is_acceptable_word(word):
                tiered["rare"][length].append(word)
                all_included.add(word)

    # Make sure all common words are included even if not in Collins
    for word in sorted(all_common):
        if 3 <= len(word) <= 7:
            length = str(len(word))
            if word not in tiered["common"][length]:
                tiered["common"][length].append(word)
                all_included.add(word)

    # Sort all lists
    for tier in tiered:
        for length in tiered[tier]:
            tiered[tier][length].sort()

    # Print statistics
    print("\nTiered dictionary statistics:")
    total_common = 0
    total_rare = 0
    for length in ["3", "4", "5", "6", "7"]:
        common_count = len(tiered["common"][length])
        rare_count = len(tiered["rare"][length])
        total_common += common_count
        total_rare += rare_count
        print(f"  {length}-letter: {common_count:,} common, {rare_count:,} rare")

    print(f"\nTotal: {total_common:,} common + {total_rare:,} rare = {total_common + total_rare:,} words")

    # Write tiered JSON
    print(f"\nWriting {OUTPUT_JSON}...")
    with open(OUTPUT_JSON, 'w', encoding='utf-8') as f:
        json.dump(tiered, f)

    # Copy to frontend
    print(f"Writing {FRONTEND_JSON}...")
    FRONTEND_JSON.parent.mkdir(parents=True, exist_ok=True)
    with open(FRONTEND_JSON, 'w', encoding='utf-8') as f:
        json.dump(tiered, f)

    # Also write flat files for backwards compatibility
    print(f"Writing flat dictionary files...")
    flat_words = sorted(all_included)

    with open(OUTPUT_TXT, 'w', encoding='utf-8') as f:
        for word in flat_words:
            f.write(word + '\n')

    with open(OUTPUT_FLAT_JSON, 'w', encoding='utf-8') as f:
        json.dump(flat_words, f)

    # Copy flat JSON to frontend too
    frontend_flat = FRONTEND_JSON.parent / "curated_dictionary.json"
    with open(frontend_flat, 'w', encoding='utf-8') as f:
        json.dump(flat_words, f)

    print(f"\nDone! Files created:")
    print(f"  - {OUTPUT_JSON} ({OUTPUT_JSON.stat().st_size:,} bytes)")
    print(f"  - {FRONTEND_JSON} ({FRONTEND_JSON.stat().st_size:,} bytes)")
    print(f"  - {OUTPUT_TXT} ({OUTPUT_TXT.stat().st_size:,} bytes)")
    print(f"  - {OUTPUT_FLAT_JSON} ({OUTPUT_FLAT_JSON.stat().st_size:,} bytes)")

    return tiered


def is_acceptable_word(word):
    """Check if a word should be included in the rare tier."""
    # Must have at least one vowel
    if not any(c in 'AEIOUY' for c in word):
        return False

    # Skip words with too many consecutive consonants
    consonants = 0
    for c in word:
        if c not in 'AEIOU':
            consonants += 1
            if consonants >= 4:
                return False
        else:
            consonants = 0

    # Skip words starting with uncommon patterns
    bad_starts = ['BV', 'CF', 'DF', 'GV', 'HV', 'JV', 'KV', 'PV', 'ZB', 'ZC', 'ZD', 'ZF']
    for pattern in bad_starts:
        if word.startswith(pattern):
            return False

    return True


